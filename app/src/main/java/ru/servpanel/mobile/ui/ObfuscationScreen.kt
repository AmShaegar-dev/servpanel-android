@Composable
fun ObfuscationScreen(vm: AppViewModel, server: ServerProfile) {
    val scope = rememberCoroutineScope()
    val context = LocalContext.current
    val auth = vm.authOf(server.id)

    var current by remember(server.id) { mutableStateOf<ObfCurrent?>(null) }
    var profiles by remember(server.id) { mutableStateOf<ObfProfiles?>(null) }
    var generated by remember { mutableStateOf<ObfGenerated?>(null) }
    var preset by remember { mutableStateOf("balanced") }
    var error by remember(server.id) { mutableStateOf<String?>(null) }
    var loading by remember(server.id) { mutableStateOf(true) }
    var reload by remember(server.id) { mutableIntStateOf(0) }
    var busy by remember { mutableStateOf(false) }
    var message by remember { mutableStateOf<String?>(null) }
    var messageOk by remember { mutableStateOf(false) }
    var applyTarget by remember { mutableStateOf<ObfProfile?>(null) }
    var applyGenerated by remember { mutableStateOf(false) }
    var regenClients by remember { mutableStateOf(true) }
    var removeMissing by remember { mutableStateOf(false) }

    LaunchedEffect(server.id, vm.refreshTick, reload) {
        if (current == null) loading = true
        error = null
        try {
            current = vm.call(server) { obfCurrent() }
            profiles = runCatching { vm.call(server) { obfProfiles() } }.getOrNull()
        } catch (e: Exception) {
            if (current == null) error = e.message ?: "Не удалось прочитать параметры обфускации"
        } finally {
            loading = false
        }
    }

    if (loading && current == null) {
        LoadingState("Читаем параметры AmneziaWG…")
        return
    }

    val cur = current
    if (cur == null) {
        Column(Modifier.padding(16.dp)) {
            ErrorState(error ?: "Нет данных", onRetry = { reload++ })
        }
        return
    }

    LazyColumn(
        modifier = Modifier.fillMaxSize(),
        contentPadding = androidx.compose.foundation.layout.PaddingValues(
            start = 16.dp, end = 16.dp, top = 12.dp, bottom = 28.dp
        ),
        verticalArrangement = Arrangement.spacedBy(12.dp)
    ) {
        item {
            ScreenHeader(
                title = "Обфускация",
                subtitle = "Параметры AmneziaWG и защита от DPI",
                trailing = {
                    IconButton(onClick = { reload++ }) {
                        Icon(Icons.Filled.Refresh, contentDescription = "Обновить", tint = PanelMuted)
                    }
                }
            )
        }

        item {
            AuditCard(
                audit = cur.audit,
                version = cur.version,
                file = cur.file
            )
        }

        item {
            PanelCard {
                SectionHeader(
                    title = "Текущие параметры",
                    subtitle = "${cur.params.size} значений"
                )
                Spacer(Modifier.height(8.dp))
                if (cur.params.isEmpty()) {
                    Text(
                        "Параметры не найдены в конфиге сервера.",
                        style = MaterialTheme.typography.bodySmall,
                        color = PanelMuted
                    )
                } else {
                    cur.params.forEach { (key, value) ->
                        InfoRow(key, value, mono = true)
                    }
                }
            }
        }

        if (auth.isAdmin) {
            item {
                PanelCard {
                    SectionHeader(
                        title = "Сгенерировать набор",
                        subtitle = "Подобрать параметры под задачу"
                    )

                    Spacer(Modifier.height(10.dp))

                    PanelDropdown(
                        label = "Пресет",
                        options = listOf("max", "balanced", "compat"),
                        selected = preset,
                        onSelect = { preset = it }
                    )

                    Spacer(Modifier.height(10.dp))

                    Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                        PanelButton(
                            text = "Сгенерировать",
                            onClick = {
                                busy = true
                                message = null
                                scope.launch {
                                    try {
                                        generated = vm.call(server) { obfGenerate(preset) }
                                    } catch (e: Exception) {
                                        messageOk = false
                                        message = e.message ?: "Не удалось сгенерировать"
                                    } finally {
                                        busy = false
                                    }
                                }
                            },
                            modifier = Modifier.weight(1f),
                            loading = busy,
                            icon = Icons.Filled.AutoAwesome
                        )
                        PanelOutlinedButton(
                            text = "Экспорт",
                            onClick = {
                                busy = true
                                scope.launch {
                                    try {
                                        val conf = vm.call(server) { obfExport("conf") }
                                        shareFile(context, "amneziawg-obf.conf", conf)
                                    } catch (e: Exception) {
                                        messageOk = false
                                        message = e.message ?: "Не удалось экспортировать"
                                    } finally {
                                        busy = false
                                    }
                                }
                            },
                            modifier = Modifier.weight(1f),
                            icon = Icons.Filled.Share
                        )
                    }

                    generated?.let { result ->
                        Spacer(Modifier.height(14.dp))
                        PanelDivider()
                        Spacer(Modifier.height(10.dp))

                        Row(verticalAlignment = Alignment.CenterVertically) {
                            Text(
                                "Сгенерировано · ${result.version}",
                                style = MaterialTheme.typography.labelMedium,
                                color = PanelMuted,
                                modifier = Modifier.weight(1f)
                            )
                            Badge("${result.audit.score}/100", scoreColor(result.audit.score))
                        }

                        Spacer(Modifier.height(8.dp))

                        result.params.forEach { (key, value) ->
                            InfoRow(key, value, mono = true)
                        }

                        Spacer(Modifier.height(10.dp))

                        ToggleRow(
                            title = "Перегенерировать клиентов",
                            subtitle = "Клиентские конфиги получат новые параметры",
                            checked = regenClients,
                            onCheckedChange = { regenClients = it }
                        )
                        ToggleRow(
                            title = "Удалить отсутствующих",
                            subtitle = "Убрать клиентов, которых нет на сервере",
                            checked = removeMissing,
                            onCheckedChange = { removeMissing = it }
                        )

                        Spacer(Modifier.height(10.dp))

                        PanelButton(
                            text = "Применить",
                            onClick = { applyGenerated = true },
                            modifier = Modifier.fillMaxWidth(),
                            enabled = result.params.isNotEmpty()
                        )
                    }
                }
            }
        }

        profiles?.let { payload ->
            val all = payload.builtin + payload.custom
            if (all.isNotEmpty()) {
                item {
                    PanelCard {
                        SectionHeader(
                            title = "Профили",
                            subtitle = "Готовые наборы параметров"
                        )
                        Spacer(Modifier.height(8.dp))
                        all.forEach { profile ->
                            Row(
                                modifier = Modifier
                                    .fillMaxWidth()
                                    .padding(vertical = 7.dp),
                                verticalAlignment = Alignment.CenterVertically
                            ) {
                                Column(Modifier.weight(1f)) {
                                    Row(verticalAlignment = Alignment.CenterVertically) {
                                        Text(
                                            profile.title,
                                            style = MaterialTheme.typography.bodyMedium,
                                            fontWeight = FontWeight.Medium,
                                            color = PanelText
                                        )
                                        if (profile.builtin) {
                                            Spacer(Modifier.width(8.dp))
                                            Badge("встроенный", PanelViolet)
                                        }
                                    }
                                    Text(
                                        buildString {
                                            append("${profile.score}/100")
                                            if (profile.note.isNotBlank()) append(" · ${profile.note}")
                                        },
                                        style = MaterialTheme.typography.labelSmall,
                                        color = PanelMuted
                                    )
                                }
                                if (auth.isAdmin) {
                                    TextButton(onClick = { applyTarget = profile }) {
                                        Text("Применить", color = PanelAccent)
                                    }
                                }
                            }
                        }
                    }
                }
            }
        }

        if (cur.audit.findings.isNotEmpty()) {
            item {
                PanelCard {
                    SectionHeader(
                        title = "Замечания аудита",
                        subtitle = "${cur.audit.findings.size} пунктов"
                    )
                    Spacer(Modifier.height(8.dp))
                    cur.audit.findings.forEach { finding ->
                        val color = when (finding.level) {
                            "error" -> PanelRed
                            "warn" -> PanelAmber
                            "ok" -> PanelGreen
                            else -> PanelMuted
                        }
                        Row(
                            modifier = Modifier
                                .fillMaxWidth()
                                .padding(vertical = 5.dp),
                            verticalAlignment = Alignment.Top
                        ) {
                            Icon(
                                if (finding.level == "ok") Icons.Filled.Check else Icons.Filled.Warning,
                                contentDescription = null,
                                tint = color,
                                modifier = Modifier
                                    .padding(top = 2.dp)
                                    .size(16.dp)
                            )
                            Spacer(Modifier.width(8.dp))
                            Column(Modifier.weight(1f)) {
                                Text(
                                    finding.title,
                                    style = MaterialTheme.typography.bodySmall,
                                    color = PanelText
                                )
                                if (finding.detail.isNotBlank()) {
                                    Text(
                                        finding.detail,
                                        style = MaterialTheme.typography.labelSmall,
                                        color = PanelMuted
                                    )
                                }
                                if (finding.fix.isNotBlank()) {
                                    Text(
                                        finding.fix,
                                        style = MaterialTheme.typography.labelSmall,
                                        color = color
                                    )
                                }
                            }
                        }
                    }
                }
            }
        }

        message?.let { text ->
            item {
                Surface(
                    shape = RoundedCornerShape(12.dp),
                    color = if (messageOk) PanelGreen.copy(alpha = 0.12f) else PanelRed.copy(alpha = 0.12f),
                    border = BorderStroke(1.dp, (if (messageOk) PanelGreen else PanelRed).copy(alpha = 0.35f)),
                    modifier = Modifier.fillMaxWidth()
                ) {
                    Text(
                        text,
                        style = MaterialTheme.typography.bodySmall,
                        color = if (messageOk) PanelGreen else PanelRed,
                        modifier = Modifier.padding(12.dp)
                    )
                }
            }
        }

        item {
            Row(verticalAlignment = Alignment.CenterVertically) {
                Icon(Icons.Filled.Tune, contentDescription = null, tint = PanelMuted, modifier = Modifier.size(15.dp))
                Spacer(Modifier.width(8.dp))
                Text(
                    "После применения параметров клиентам нужны новые конфиги.",
                    style = MaterialTheme.typography.labelSmall,
                    color = PanelMuted
                )
            }
        }
    }

    if (applyGenerated) {
        val result = generated
        AlertDialog(
            onDismissRequest = { applyGenerated = false },
            containerColor = PanelElevated,
            title = { Text("Применить параметры?") },
            text = {
                Text(
                    "Серверный конфиг будет обновлён. " +
                        (if (regenClients) "Клиентские конфиги будут перегенерированы. " else "") +
                        "Убедитесь, что клиенты получат новые ключи.",
                    style = MaterialTheme.typography.bodySmall,
                    color = PanelMuted
                )
            },
            confirmButton = {
                TextButton(onClick = {
                    applyGenerated = false
                    if (result == null) return@TextButton
                    busy = true
                    message = null
                    scope.launch {
                        try {
                            val applied = vm.call(server) {
                                obfApply(result.params, regenClients, removeMissing)
                            }
                            messageOk = true
                            message = buildString {
                                append("Параметры применены")
                                if (applied.regenerated != null) append(", клиентов перегенерировано: ${applied.regenerated}")
                                if (applied.removed.isNotEmpty()) append(", удалено: ${applied.removed.size}")
                            }
                            generated = null
                            reload++
                        } catch (e: Exception) {
                            messageOk = false
                            message = e.message ?: "Не удалось применить параметры"
                        } finally {
                            busy = false
                        }
                    }
                }) { Text("Применить", color = PanelAccent) }
            },
            dismissButton = {
                TextButton(onClick = { applyGenerated = false }) { Text("Отмена") }
            }
        )
    }

    applyTarget?.let { profile ->
        AlertDialog(
            onDismissRequest = { applyTarget = null },
            containerColor = PanelElevated,
            title = { Text("Применить профиль?") },
            text = {
                Column {
                    Text(
                        "Профиль «${profile.title}» будет применён к серверному конфигу.",
                        style = MaterialTheme.typography.bodySmall,
                        color = PanelMuted
                    )
                    Spacer(Modifier.height(8.dp))
                    ToggleRow(
                        title = "Перегенерировать клиентов",
                        checked = regenClients,
                        onCheckedChange = { regenClients = it }
                    )
                    ToggleRow(
                        title = "Удалить отсутствующих",
                        checked = removeMissing,
                        onCheckedChange = { removeMissing = it }
                    )
                }
            },
            confirmButton = {
                TextButton(onClick = {
                    applyTarget = null
                    busy = true
                    message = null
                    scope.launch {
                        try {
                            val applied = vm.call(server) {
                                obfApplyProfile(profile.name, regenClients, removeMissing)
                            }
                            messageOk = true
                            message = "Профиль применён" +
                                (applied.regenerated?.let { ", клиентов: $it" } ?: "")
                            reload++
                        } catch (e: Exception) {
                            messageOk = false
                            message = e.message ?: "Не удалось применить профиль"
                        } finally {
                            busy = false
                        }
                    }
                }) { Text("Применить", color = PanelAccent) }
            },
            dismissButton = {
                TextButton(onClick = { applyTarget = null }) { Text("Отмена") }
            }
        )
    }
}

@Composable
private fun AuditCard(audit: ObfAudit, version: String, file: String) {
    val color = scoreColor(audit.score)
    PanelCard {
        Row(verticalAlignment = Alignment.CenterVertically) {
            Surface(
                shape = RoundedCornerShape(14.dp),
                color = color.copy(alpha = 0.12f),
                border = BorderStroke(1.dp, color.copy(alpha = 0.35f)),
                modifier = Modifier.size(58.dp)
            ) {
                Column(
                    horizontalAlignment = Alignment.CenterHorizontally,
                    verticalArrangement = Arrangement.Center,
                    modifier = Modifier.fillMaxSize()
                ) {
                    Text(
                        audit.score.toString(),
                        style = MaterialTheme.typography.titleMedium,
                        fontWeight = FontWeight.Bold,
                        color = color
                    )
                    Text(
                        "из 100",
                        style = MaterialTheme.typography.labelSmall,
                        color = PanelMuted
                    )
                }
            }
            Spacer(Modifier.width(14.dp))
            Column(Modifier.weight(1f)) {
                Text(
                    "Устойчивость к DPI",
                    style = MaterialTheme.typography.titleSmall,
                    fontWeight = FontWeight.SemiBold,
                    color = PanelText
                )
                Text(
                    audit.levelLabel.ifBlank { "Оценка недоступна" },
                    style = MaterialTheme.typography.bodySmall,
                    color = color
                )
                Text(
                    "AmneziaWG ${version.ifBlank { audit.version }}",
                    style = MaterialTheme.typography.labelSmall,
                    color = PanelMuted
                )
            }
        }

        if (audit.summary().isNotBlank()) {
            Spacer(Modifier.height(10.dp))
            Text(
                audit.summary(),
                style = MaterialTheme.typography.labelSmall.copy(fontFamily = FontFamily.Monospace),
                color = PanelMuted
            )
        }

        if (file.isNotBlank()) {
            Spacer(Modifier.height(6.dp))
            Text(
                file,
                style = MaterialTheme.typography.labelSmall,
                color = PanelMuted
            )
        }
    }
}

private fun ObfAudit.summary(): String = buildList {
    if (shared.isNotBlank()) add("общие: $shared")
    if (client.isNotBlank()) add("клиент: $client")
    if (cps > 0) add("CPS: $cps")
    if (hpk) add("HPK: да")
}.joinToString(" · ")

private fun scoreColor(score: Int) = when {
    score >= 80 -> PanelGreen
    score >= 55 -> PanelAmber
    else -> PanelRed
}
